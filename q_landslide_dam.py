    def _read_dem_array(self, layer):
        """Legge la banda 1 del raster come matrice float32, con i NoData convertiti in NaN."""
        ds = gdal.Open(layer.source())
        if ds is not None:
            band = ds.GetRasterBand(1)
            dem_array = band.ReadAsArray().astype(np.float32)
            nodata_val = band.GetNoDataValue()
            ds = None
            if nodata_val is not None:
                dem_array[dem_array == nodata_val] = np.nan
            return dem_array

        # Fallback per sorgenti non leggibili direttamente da GDAL
        provider = layer.dataProvider()
        cols = layer.width()
        rows = layer.height()
        block = provider.block(1, layer.extent(), cols, rows)
        nodata_val = provider.sourceNoDataValue(1)
        dem_array = np.zeros((rows, cols), dtype=np.float32)
        for r in range(rows):
            for c in range(cols):
                val = block.value(r, c)
                dem_array[r, c] = val if val != nodata_val else np.nan
        return dem_array

    def _rotated_distances(self, layer, center_point, direction_deg):
        """
        Distanze di ogni cella dal punto centrale: lungo l'asse dello sbarramento
        (d_parallel), in direzione monte-valle (d_perpendicular) ed euclidea.
        """
        extent = layer.extent()
        cols = layer.width()
        rows = layer.height()
        pixel_size_x = layer.rasterUnitsPerPixelX()
        pixel_size_y = layer.rasterUnitsPerPixelY()

        x_coords = np.linspace(extent.xMinimum() + pixel_size_x / 2.0, extent.xMaximum() - pixel_size_x / 2.0, cols)
        y_coords = np.linspace(extent.yMaximum() - pixel_size_y / 2.0, extent.yMinimum() + pixel_size_y / 2.0, rows)
        X, Y = np.meshgrid(x_coords, y_coords)

        dX = X - center_point.x()
        dY = Y - center_point.y()

        azimuth_rad = np.radians(direction_deg)
        d_parallel = dX * np.sin(azimuth_rad) + dY * np.cos(azimuth_rad)
        d_perpendicular = dX * np.cos(azimuth_rad) - dY * np.sin(azimuth_rad)
        distance = np.sqrt(dX ** 2 + dY ** 2)

        return d_parallel, d_perpendicular, distance

    def save_and_load_raster(self, numpy_array, reference_layer, output_path, layer_name=None,
                             nodata_value=None, hillshade=False, color_range=None):
        """
        Salva la matrice NumPy come file GeoTIFF mantenendo il CRS, le dimensioni
        e il geotransform del DEM di riferimento, poi lo carica nella TOC di QGIS.
        Con color_range=(min, max) applica uno stile a falsi colori limitato a
        quell'intervallo: i valori esterni non vengono disegnati.
        """
        provider = reference_layer.dataProvider()
        extent = reference_layer.extent()
        cols = reference_layer.width()
        rows = reference_layer.height()

        crs = reference_layer.crs()
        pixel_size_x = reference_layer.rasterUnitsPerPixelX()
        pixel_size_y = reference_layer.rasterUnitsPerPixelY()

        geotransform = (
            extent.xMinimum(),
            pixel_size_x,
            0.0,
            extent.yMaximum(),
            0.0,
            -pixel_size_y
        )

        driver = gdal.GetDriverByName('GTiff')
        out_ds = driver.Create(output_path, cols, rows, 1, gdal.GDT_Float32)
        out_ds.SetGeoTransform(geotransform)

        srs = osr.SpatialReference()
        srs.ImportFromWkt(crs.toWkt())
        out_ds.SetProjection(srs.ExportToWkt())

        band = out_ds.GetRasterBand(1)
        nodata_val = nodata_value if nodata_value is not None else provider.sourceNoDataValue(1)

        if nodata_val is not None:
            band.SetNoDataValue(nodata_val)
            numpy_array = np.nan_to_num(numpy_array, nan=nodata_val)

        band.WriteArray(numpy_array)
        band.FlushCache()
        out_ds = None  # Rilascia il file da GDAL

        # Caricamento nella TOC
        if layer_name is None:
            layer_name = self.tr("DEM Modified")
        new_layer = QgsRasterLayer(output_path, layer_name)
        if new_layer.isValid():
            if hillshade:
                # Visualizzazione a rilievo ombreggiato: sole da NW (azimut 315°) a 45° di altezza
                renderer = QgsHillshadeRenderer(new_layer.dataProvider(), 1, 315.0, 45.0)
                renderer.setZFactor(1.0)
                new_layer.setRenderer(renderer)
            elif color_range is not None:
                new_layer.setRenderer(self._pseudocolor_renderer(new_layer, *color_range))
            QgsProject.instance().addMapLayer(new_layer)
            return new_layer
        else:
            self.iface.messageBar().pushMessage(
                self.tr("Error"),
                self.tr("Unable to load the generated raster."),
                Qgis.Critical
            )
            return None

    def _pseudocolor_renderer(self, layer, min_value, max_value):
        """
        Stile a falsi colori continuo da min_value a max_value (giallo chiaro -> marrone scuro).
        Con clip attivo i valori fuori dall'intervallo restano trasparenti.
        """
        if max_value <= min_value:
            max_value = min_value + 1.0
        colors = ['#ffffcc', '#fed976', '#fd8d3c', '#e31a1c', '#800026']
        step = (max_value - min_value) / (len(colors) - 1)
        items = [QgsColorRampShader.ColorRampItem(min_value + i * step, QColor(color),
                                                  f"{min_value + i * step:.1f}")
                 for i, color in enumerate(colors)]

        ramp_shader = QgsColorRampShader(min_value, max_value)
        ramp_shader.setColorRampType(QgsColorRampShader.Interpolated)
        ramp_shader.setColorRampItemList(items)
        ramp_shader.setClip(True)

        shader = QgsRasterShader(min_value, max_value)
        shader.setRasterShaderFunction(ramp_shader)

        renderer = QgsSingleBandPseudoColorRenderer(layer.dataProvider(), 1, shader)
        renderer.setClassificationMin(min_value)
        renderer.setClassificationMax(max_value)
        return renderer

    def calculate_landslide_dam_wedge(self, dem_layer, center_point, direction_deg,
                                      side_dip_deg, crest_slope_deg, target_volume_m3,
                                      step_h=0.2, max_iterations=3000, max_radius_m=400.0):

        extent = dem_layer.extent()
        cols = dem_layer.width()
        rows = dem_layer.height()

        pixel_size_x = dem_layer.rasterUnitsPerPixelX()
        pixel_size_y = dem_layer.rasterUnitsPerPixelY()
        cell_area = pixel_size_x * pixel_size_y

        # 1. Carica la matrice del DEM di input
        dem_array = self._read_dem_array(dem_layer)
        mask_valid = ~np.isnan(dem_array)

        # 2. Distanze ruotate rispetto alla direzione della diga e distanza dal punto cliccato
        d_parallel, d_perpendicular, distance_from_center = self._rotated_distances(
            dem_layer, center_point, direction_deg)
        x0, y0 = center_point.x(), center_point.y()

        tan_side_dip = np.tan(np.radians(side_dip_deg))
        tan_crest_slope = np.tan(np.radians(crest_slope_deg))

        d_parallel_abs = np.abs(d_parallel)
        d_perpendicular_abs = np.abs(d_perpendicular)

        # 3. Quota iniziale nel punto centrale
        col_c = int((x0 - extent.xMinimum()) / pixel_size_x)
        row_c = int((extent.yMaximum() - y0) / pixel_size_y)

        if 0 <= col_c < cols and 0 <= row_c < rows:
            start_elevation = dem_array[row_c, col_c]
            if np.isnan(start_elevation):
                start_elevation = np.nanmin(dem_array)
        else:
            start_elevation = np.nanmin(dem_array)

        h = 0.0
        calculated_volume = 0.0
        iteration = 0

        final_dam_dem = np.copy(dem_array)
        thickness_array = np.zeros_like(dem_array)

        # 4. Ciclo di accrescimento progressivo confinato nel raggio locale
        while calculated_volume < target_volume_m3 and iteration < max_iterations:
            h += step_h
            current_crest_elevation = start_elevation + h

            dam_surface = current_crest_elevation - (d_parallel_abs * tan_crest_slope) - (
                    d_perpendicular_abs * tan_side_dip)

            # Maschera vincolata al raggio impostato dall'utente nei settings
            valid_wedge = mask_valid & (distance_from_center <= max_radius_m) & (dam_surface > dem_array)

            thickness = np.where(valid_wedge, dam_surface - dem_array, 0.0)
            calculated_volume = np.sum(thickness) * cell_area

            thickness_array = thickness
            final_dam_dem = np.where(thickness > 0, dam_surface, dem_array)

            iteration += 1

        return final_dam_dem, thickness_array, calculated_volume, iteration, dem_array


    def on_dialog_accepted(self):
        """Metodo eseguito quando l'utente preme OK sulla finestra principale."""

        # 1. Recupera il layer raster DEM selezionato
        dem_layer = self.dlg.DEM_raster_ComboBox.currentLayer()
        if not dem_layer:
            self.iface.messageBar().pushMessage(
                self.tr("Warning"),
                self.tr("Please select a valid DEM."),
                Qgis.Warning
            )
            return

        # Il DEM deve essere in un sistema proiettato metrico: con coordinate geografiche
        # (lat/lon) o unità diverse dal metro distanze, pendenze e volumi sarebbero errati
        crs = dem_layer.crs()
        if not crs.isValid() or crs.isGeographic() or crs.mapUnits() != QgsUnitTypes.DistanceMeters:
            crs_name = crs.authid() or crs.description() or self.tr("undefined")
            self.iface.messageBar().pushMessage(
                self.tr("Warning"),
                self.tr("The DEM '{dem}' uses the CRS {crs}, which is not projected in meters. "
                        "The plugin only works with rasters in a projected metric CRS (e.g. UTM): "
                        "reproject the DEM (Raster > Projections > Warp (Reproject)) and try again."
                        ).format(dem=dem_layer.name(), crs=crs_name),
                Qgis.Warning
            )
            return

        # Pseudo-Mercator (Web Mercator) è in metri ma deforma le distanze di 1/cos(lat):
        # aree e volumi risulterebbero sovrastimati, quindi non è ammesso
        proj = crs.toProj().replace(' ', '')
        is_pseudo_mercator = (crs.authid().upper() in PSEUDO_MERCATOR_AUTHIDS
                              or ('+proj=merc' in proj and '+a=6378137' in proj and '+b=6378137' in proj))
        if is_pseudo_mercator:
            self.iface.messageBar().pushMessage(
                self.tr("Warning"),
                self.tr("The DEM '{dem}' is in Pseudo-Mercator ({crs}), which distorts distances and areas "
                        "(at Italian latitudes volumes come out about twice as large). "
                        "Reproject the DEM to a local projected metric CRS (e.g. UTM) and try again."
                        ).format(dem=dem_layer.name(), crs=crs.authid() or crs.description()),
                Qgis.Warning
            )
            return

        direction = self.dlg.DirectionBox.value()
        side_dip = self.dlg.InclinationBox.value()
        crest_slope = self.dlg.CrestSlopeBox.value()
        volume = self.dlg.VolumeBox.value()

        # --- RECUPERO COORDINATE DALLE SPINBOX DELLA GUI ---
        x_coord = self.dlg.spin_x.value()
        y_coord = self.dlg.spin_y.value()

        # Controllo di sicurezza: verifica che le coordinate siano inserite
        if x_coord == 0 and y_coord == 0:
            self.iface.messageBar().pushMessage(
                self.tr("Warning"),
                self.tr("Enter the X and Y coordinates or pick a point on the map."),
                Qgis.Warning
            )
            return

        center_point = QgsPointXY(x_coord, y_coord)

        # Esecuzione del calcolo
        try:
            final_dem, thickness, vol_calc, num_iter, dem_array = self.calculate_landslide_dam_wedge(
                dem_layer=dem_layer,
                center_point=center_point,
                direction_deg=direction,
                side_dip_deg=side_dip,
                crest_slope_deg=crest_slope,
                target_volume_m3=volume,
                step_h=self.step_h,
                max_iterations=self.max_iterations,
                max_radius_m=self.max_radius_m
            )
        except Exception as e:
            self.iface.messageBar().pushMessage(
                self.tr("Calculation error"),
                self.tr("Error while computing the wedge: {error}").format(error=str(e)),
                Qgis.Critical
            )
            return

        # Tabella dei dati dettagliati e punti di controllo del lago nella TOC (opzionali)
        detail_layers = self.dlg.chk_detail_layers.isChecked()

        # --- SCELTA PERCORSO DI SALVATAGGIO (TEMPORANEO O PERMANENTE) ---
        if self.dlg.chk_save_permanent.isChecked():
            output_file, _ = QFileDialog.getSaveFileName(
                self.dlg,
                self.tr("Save Landslide Dam DEM"),
                "",
                self.tr("GeoTIFF Files (*.tif);;All Files (*)")
            )

            if not output_file:
                return

            if not output_file.lower().endswith('.tif'):
                output_file += '.tif'
        else:
            temp_dir = tempfile.gettempdir()
            timestamp = int(time.time())
            filename = f"landslide_dam_{timestamp}.tif"
            output_file = os.path.join(temp_dir, filename)

            # Salva su disco e carica nella TOC di QGIS
        loaded_layer = self.save_and_load_raster(
            numpy_array=final_dem,
            reference_layer=dem_layer,
            output_path=output_file,
            layer_name=self.tr("Dam DEM ({volume} m³)").format(volume=f"{vol_calc:.0f}"),
            hillshade=True
        )

        # Messaggio di successo
        if loaded_layer:
            self.iface.messageBar().pushMessage(
                "Q-LandslideDam",
                self.tr("Iterations: {iters} | Target volume: {target} m³ | Computed volume: {computed} m³").format(
                    iters=num_iter, target=volume, computed=f"{vol_calc:.1f}"),
                Qgis.Info
            )

            # Raster del solo cuneo: spessore del deposito (DEM modificato - DEM originale),
            # NoData fuori dal corpo della diga
            max_thickness = float(np.nanmax(thickness)) if np.any(thickness > 0) else 0.0
            self.save_and_load_raster(
                numpy_array=np.where(thickness > 0, thickness, np.nan),
                reference_layer=dem_layer,
                output_path=os.path.splitext(output_file)[0] + "_wedge_thickness.tif",
                layer_name=self.tr("Wedge thickness (max {thickness} m)").format(
                    thickness=f"{max_thickness:.1f}"),
                nodata_value=-9999.0,
                color_range=(0.0, max_thickness)
            )

            # =========================================================
            # 2. LAGO DI SBARRAMENTO A MONTE (r.lake di GRASS)
            # =========================================================
            lake_output = os.path.splitext(output_file)[0] + "_lake.tif"
            lake_error = None
            try:
                lake = self.calculate_lake_basin(
                    dem_layer=dem_layer,
                    dem_array=dem_array,
                    final_dem=final_dem,
                    thickness_array=thickness,
                    modified_dem_layer=loaded_layer,
                    output_path=lake_output,
                    add_control_points=detail_layers
                )
            except Exception as e:
                self.iface.messageBar().pushMessage(
                    self.tr("Lake error"),
                    self.tr("Dammed lake calculation failed: {error}").format(error=str(e)),
                    Qgis.Warning
                )
                lake = None
                lake_error = str(e)

            # =========================================================
            # 3. TABELLA RIEPILOGATIVA DEL RUN (layer temporaneo senza geometria)
            # =========================================================
            cell_area = dem_layer.rasterUnitsPerPixelX() * dem_layer.rasterUnitsPerPixelY()
            run_params = {
                'dem_layer': dem_layer, 'x': x_coord, 'y': y_coord, 'direction': direction,
                'side_dip': side_dip, 'crest_slope': crest_slope, 'target_volume': volume,
                'output_file': output_file,
            }
            dam_results = {
                'iterations': num_iter, 'volume': vol_calc,
                'max_thickness': max_thickness,
                'footprint_area': float(np.count_nonzero(thickness > 0)) * cell_area,
            }
            results_table = None
            if detail_layers:
                results_table = self._add_results_table(run_params, dam_results, lake, lake_error)
                # Aggiunto per ultimo, così il punto della frana resta visibile sopra gli altri layer
                self._add_landslide_point_layer(center_point, dem_layer, loaded_layer, run_params, dam_results)

            if lake is not None:
                seed_x, seed_y = lake['seed']
                if lake['status'] == 'not_effective':
                    self.iface.messageBar().pushMessage(
                        "Q-LandslideDam",
                        self.tr("The dam does not block the valley: from the seed ({x}, {y}, elevation {z} m) "
                                "water flows out through {exit} without impoundment.").format(
                            x=f"{seed_x:.1f}", y=f"{seed_y:.1f}", z=f"{lake['seed_z']:.2f}",
                            exit=lake['exit_description'])
                        + (" " + self.tr("Check the '{layer}' layer.").format(
                            layer=self.tr("Lake - control points")) if detail_layers else ""),
                        Qgis.Warning
                    )
                else:
                    lake_msg = self.tr("Lake: level {level} m | volume {volume} m³ | area {area} ha | "
                                       "max depth {depth} m | seed {x}, {y}").format(
                        level=f"{lake['level']:.2f}", volume=f"{lake['volume']:.0f}",
                        area=f"{lake['area'] / 10000.0:.2f}", depth=f"{lake['max_depth']:.1f}",
                        x=f"{seed_x:.1f}", y=f"{seed_y:.1f}")
                    if lake['status'] == 'border':
                        self.iface.messageBar().pushMessage(
                            "Q-LandslideDam",
                            lake_msg + " | " + self.tr("WARNING: the lake reaches the DEM edge and may be "
                                                       "truncated, use a larger DEM."),
                            Qgis.Warning
                        )
                    else:
                        self.iface.messageBar().pushMessage("Q-LandslideDam", lake_msg, Qgis.Info)

            if results_table is not None:
                self.iface.messageBar().pushMessage(
                    "Q-LandslideDam",
                    self.tr("All run details are in the table '{table}' (open its attribute table).").format(
                        table=results_table.name()),
                    Qgis.Info
                )

        # Chiude la finestra al termine dell'operazione
        self.dlg.close()

    def _rlake_algorithm_id(self):
        """Id di r.lake nel Processing: 'grass:' da QGIS 3.36, 'grass7:' nelle versioni precedenti."""
        registry = QgsApplication.processingRegistry()
        for alg_id in ('grass:r.lake', 'grass7:r.lake'):
            if registry.algorithmById(alg_id) is not None:
                return alg_id
        return None

    def _add_control_points_layer(self, points, crs):
        """
        Aggiunge alla TOC un layer temporaneo con i punti di controllo del lago
        (seed, punto di valle, punto di tracimazione) e i relativi attributi.
        """
        layer = QgsVectorLayer("Point", self.tr("Lake - control points"), "memory")
        layer.setCrs(crs)
        provider = layer.dataProvider()
        provider.addAttributes([
            QgsField("role", QVariant.String),
            QgsField("x", QVariant.Double),
            QgsField("y", QVariant.Double),
            QgsField("dem_elev", QVariant.Double),
            QgsField("spill_level", QVariant.Double),
            QgsField("status", QVariant.String),
            QgsField("note", QVariant.String),
        ])
        layer.updateFields()

        features = []
        for point in points:
            feature = QgsFeature(layer.fields())
            feature.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(point['x'], point['y'])))
            feature.setAttributes([point['role'], point['x'], point['y'], point['dem_elev'],
                                   point['spill_level'], point['status'], point['note']])
            features.append(feature)
        provider.addFeatures(features)
        layer.updateExtents()
        QgsProject.instance().addMapLayer(layer)
        return layer

    def _add_landslide_point_layer(self, center_point, dem_layer, modified_dem_layer, run_params, dam_results):
        """
        Aggiunge alla TOC un layer temporaneo con il punto della frana (punto cliccato
        sulla mappa o inserito nelle coordinate), con i parametri e i risultati del cuneo.
        """
        def sample(layer, point):
            value, ok = layer.dataProvider().sample(point, 1)
            return float(value) if ok else None

        layer = QgsVectorLayer("Point", self.tr("Landslide point"), "memory")
        layer.setCrs(dem_layer.crs())
        provider = layer.dataProvider()
        provider.addAttributes([
            QgsField("x", QVariant.Double),
            QgsField("y", QVariant.Double),
            QgsField("dem_elev", QVariant.Double),
            QgsField("dam_elev", QVariant.Double),
            QgsField("direction", QVariant.Double),
            QgsField("side_dip", QVariant.Double),
            QgsField("crest_slp", QVariant.Double),
            QgsField("target_vol", QVariant.Double),
            QgsField("dam_vol", QVariant.Double),
            QgsField("max_thick", QVariant.Double),
        ])
        layer.updateFields()

        feature = QgsFeature(layer.fields())
        feature.setGeometry(QgsGeometry.fromPointXY(center_point))
        feature.setAttributes([
            center_point.x(), center_point.y(),
            sample(dem_layer, center_point), sample(modified_dem_layer, center_point),
            float(run_params['direction']), float(run_params['side_dip']), float(run_params['crest_slope']),
            float(run_params['target_volume']), float(dam_results['volume']),
            float(dam_results['max_thickness']),
        ])
        provider.addFeatures([feature])
        layer.updateExtents()
        QgsProject.instance().addMapLayer(layer)
        return layer

    def _add_results_table(self, run_params, dam_results, lake, lake_error=None):
        """
        Aggiunge alla TOC una tabella temporanea (senza geometria) con tutti i dati del run:
        input, impostazioni, risultati del cuneo e del lago. Il nome contiene data e ora del run.
        """
        run_time = time.strftime("%Y-%m-%d %H:%M:%S")
        dem_layer = run_params['dem_layer']
        rows = []

        def add(section, parameter, value=None, unit="", text=""):
            rows.append((section, parameter, None if value is None else float(value), unit, text))

        # Run
        add(self.tr("Run"), self.tr("Date and time"), text=run_time)
        add(self.tr("Run"), self.tr("DEM layer"), text=dem_layer.name())
        add(self.tr("Run"), self.tr("Input DEM file"), text=dem_layer.source())
        add(self.tr("Run"), self.tr("DEM CRS"), text=dem_layer.crs().authid() or dem_layer.crs().description())
        add(self.tr("Run"), self.tr("DEM cell size X"), dem_layer.rasterUnitsPerPixelX(), "m")
        add(self.tr("Run"), self.tr("DEM cell size Y"), dem_layer.rasterUnitsPerPixelY(), "m")
        add(self.tr("Run"), self.tr("Output dam DEM file"), text=run_params['output_file'])

        # Input
        add(self.tr("Input"), self.tr("Landslide point X"), run_params['x'], "m")
        add(self.tr("Input"), self.tr("Landslide point Y"), run_params['y'], "m")
        add(self.tr("Input"), self.tr("Landslide direction"), run_params['direction'], "°")
        add(self.tr("Input"), self.tr("Face slope (upstream/downstream)"), run_params['side_dip'], "°")
        add(self.tr("Input"), self.tr("Crest slope (along axis)"), run_params['crest_slope'], "°")
        add(self.tr("Input"), self.tr("Target landslide volume"), run_params['target_volume'], "m³")

        # Settings
        add(self.tr("Settings"), self.tr("Vertical step"), self.step_h, "m")
        add(self.tr("Settings"), self.tr("Max iterations"), self.max_iterations)
        add(self.tr("Settings"), self.tr("Max radius"), self.max_radius_m, "m")

        # Dam
        target = run_params['target_volume']
        add(self.tr("Dam"), self.tr("Iterations"), dam_results['iterations'])
        add(self.tr("Dam"), self.tr("Computed landslide volume"), dam_results['volume'], "m³")
        if target:
            add(self.tr("Dam"), self.tr("Volume difference vs target"), (dam_results['volume'] - target) / target * 100.0, "%")
        add(self.tr("Dam"), self.tr("Max deposit thickness"), dam_results['max_thickness'], "m")
        add(self.tr("Dam"), self.tr("Dam footprint area"), dam_results['footprint_area'], "m²")

        # Lake
        if lake is None:
            add(self.tr("Lake"), self.tr("Status"), text="error")
            add(self.tr("Lake"), self.tr("Error"), text=lake_error or self.tr("lake not computed"))
        else:
            add(self.tr("Lake"), self.tr("Status"), text=lake['status'])
            add(self.tr("Lake"), self.tr("Note"), text=lake['note'])
            add(self.tr("Lake"), self.tr("Max dam crest elevation"), lake['max_crest'], self.tr("m a.s.l."))
            add(self.tr("Lake"), self.tr("Spillway level (water surface)"), lake['level'], self.tr("m a.s.l."))
            add(self.tr("Lake"), self.tr("Freeboard (crest − spillway)"), lake['max_crest'] - lake['level'], "m")
            add(self.tr("Lake"), self.tr("Spill outlet"), text=lake['exit_description'])
            if lake['status'] != 'not_effective':
                add(self.tr("Lake"), self.tr("Lake volume (numpy)"), lake['volume'], "m³")
                if lake['rlake_volume'] is not None:
                    add(self.tr("Lake"), self.tr("Lake volume (r.lake)"), lake['rlake_volume'], "m³")
                add(self.tr("Lake"), self.tr("Lake area"), lake['area'], "m²")
                add(self.tr("Lake"), self.tr("Lake area"), lake['area'] / 10000.0, "ha")
                add(self.tr("Lake"), self.tr("Max water depth"), lake['max_depth'], "m")
                if lake['layer'] is not None:
                    add(self.tr("Lake"), self.tr("Lake raster file"), text=lake['layer'].source())
            seed_x, seed_y = lake['seed']
            outlet_x, outlet_y = lake['outlet']
            add(self.tr("Lake"), self.tr("Upstream seed X"), seed_x, "m")
            add(self.tr("Lake"), self.tr("Upstream seed Y"), seed_y, "m")
            add(self.tr("Lake"), self.tr("Upstream seed elevation"), lake['seed_z'], self.tr("m a.s.l."))
            add(self.tr("Lake"), self.tr("Downstream point X"), outlet_x, "m")
            add(self.tr("Lake"), self.tr("Downstream point Y"), outlet_y, "m")
            add(self.tr("Lake"), self.tr("Downstream point elevation"), lake['outlet_z'], self.tr("m a.s.l."))

        layer = QgsVectorLayer("None", self.tr("Q-LandslideDam results {time}").format(time=run_time), "memory")
        provider = layer.dataProvider()
        provider.addAttributes([
            QgsField("section", QVariant.String),
            QgsField("parameter", QVariant.String),
            QgsField("value", QVariant.Double),
            QgsField("unit", QVariant.String),
            QgsField("text", QVariant.String),
        ])
        layer.updateFields()

        features = []
        for row in rows:
            feature = QgsFeature(layer.fields())
            feature.setAttributes(list(row))
            features.append(feature)
        provider.addFeatures(features)
        QgsProject.instance().addMapLayer(layer)
        return layer

    def _raster_volume(self, raster_path, cell_area):
        """Volume (m³) di un raster delle profondità: somma delle celle positive per l'area della cella."""
        ds = gdal.Open(raster_path)
        band = ds.GetRasterBand(1)
        depth = band.ReadAsArray().astype(np.float64)
        nodata_val = band.GetNoDataValue()
        ds = None
        valid = np.isfinite(depth) & (depth > 0)
        if nodata_val is not None:
            valid &= depth != nodata_val
        return float(np.sum(depth[valid])) * cell_area

    def calculate_lake_basin(self, dem_layer, dem_array, final_dem, thickness_array,
                             modified_dem_layer, output_path, add_control_points=True):
        """
        Calcola il lago di sbarramento a monte del cuneo senza input dell'utente:
        1. seed point e punto di valle dove l'alveo attraversa l'anello attorno al cuneo;
        2. quota di sfioro per bisezione (quota massima senza tracimazione verso valle);
        3. raster delle profondità con r.lake (o in numpy se GRASS non è disponibile);
        4. volume, area e profondità massima del lago.
        Se add_control_points è True i punti di controllo vengono caricati nella TOC,
        anche se il lago non si forma.
        """
        extent = dem_layer.extent()
        pixel_size_x = dem_layer.rasterUnitsPerPixelX()
        pixel_size_y = dem_layer.rasterUnitsPerPixelY()
        cell_area = pixel_size_x * pixel_size_y

        def cell_center(rc):
            return (extent.xMinimum() + (rc[1] + 0.5) * pixel_size_x,
                    extent.yMaximum() - (rc[0] + 0.5) * pixel_size_y)

        # 1. Seed point a monte e punto di riferimento a valle
        seed_rc, outlet_rc, persistence = lake_utils.find_seed_and_outlet(dem_array, thickness_array)
        seed_x, seed_y = cell_center(seed_rc)
        outlet_x, outlet_y = cell_center(outlet_rc)

        # 2. Quota di sfioro
        max_level = float(np.nanmax(final_dem[thickness_array > 0]))
        spill = lake_utils.compute_spill_level(final_dem, seed_rc, outlet_rc, max_level)
        level = spill['level']
        status = spill['status']
        exit_rc = spill['exit_rc']

        if exit_rc is None:
            exit_description = self.tr("no outlet")
        elif tuple(exit_rc) == tuple(outlet_rc):
            exit_description = self.tr("the downstream point")
        else:
            exit_description = self.tr("the DEM edge / NoData")

        result = {'status': status, 'level': level, 'seed': (seed_x, seed_y),
                  'seed_z': float(final_dem[seed_rc]), 'exit_description': exit_description,
                  'outlet': (outlet_x, outlet_y), 'outlet_z': float(dem_array[outlet_rc]),
                  'max_crest': max_level,
                  'volume': 0.0, 'area': 0.0, 'max_depth': 0.0, 'layer': None, 'rlake_volume': None}

        # Punti di controllo, sempre caricati nella TOC
        status_note = {
            'ok': self.tr("Lake impounded, spillway towards downstream"),
            'border': self.tr("Spill occurs towards the DEM edge: lake probably truncated"),
            'not_effective': self.tr("Water from the seed reaches {exit} without impoundment").format(
                exit=exit_description),
        }[status]
        result['note'] = status_note
        points = [
            {'role': self.tr("Upstream seed"), 'x': seed_x, 'y': seed_y, 'dem_elev': float(dem_array[seed_rc]),
             'spill_level': level, 'status': status,
             'note': status_note + " | " + self.tr("channel persistence {value} m").format(
                 value=f"{persistence:.2f}")},
            {'role': self.tr("Downstream point"), 'x': outlet_x, 'y': outlet_y,
             'dem_elev': float(dem_array[outlet_rc]), 'spill_level': level, 'status': status,
             'note': self.tr("Channel outlet downstream of the wedge")},
        ]
        if exit_rc is not None and tuple(exit_rc) != tuple(outlet_rc):
            exit_x, exit_y = cell_center(exit_rc)
            points.append({'role': self.tr("Overflow point"), 'x': exit_x, 'y': exit_y,
                           'dem_elev': float(final_dem[exit_rc]), 'spill_level': level, 'status': status,
                           'note': self.tr("Cell where water leaves the domain")})

        log_msg = (f"Lake [{status}]: spill level {level:.2f} m (max crest {max_level:.2f} m) | "
                   f"seed {seed_x:.2f}, {seed_y:.2f} (z {float(dem_array[seed_rc]):.2f} m) | "
                   f"downstream {outlet_x:.2f}, {outlet_y:.2f} (z {float(dem_array[outlet_rc]):.2f} m) | "
                   f"outlet: {exit_description} | internal NoData: {spill['internal_nodata_cells']} cells")
        QgsMessageLog.logMessage(log_msg, "Q-LandslideDam", Qgis.Info)

        if status == 'not_effective':
            if add_control_points:
                self._add_control_points_layer(points, dem_layer.crs())
            return result

        depth, volume, area, max_depth = lake_utils.lake_statistics(
            final_dem, spill['lake_mask'], level, cell_area)
        result.update(volume=volume, area=area, max_depth=max_depth)

        layer_name = self.tr("Lake (W = {level} m, V = {volume} m³)").format(
            level=f"{level:.1f}", volume=f"{volume:.0f}")

        # 3. Raster del lago con r.lake di GRASS
        lake_layer = None
        alg_id = self._rlake_algorithm_id()
        if alg_id is not None:
            authid = dem_layer.crs().authid()
            coordinates = f"{seed_x},{seed_y} [{authid}]" if authid else f"{seed_x},{seed_y}"
            try:
                rlake = processing.run(alg_id, {
                    'elevation': modified_dem_layer,
                    'water_level': level,
                    'coordinates': coordinates,
                    'lake': output_path
                })
                lake_layer = QgsRasterLayer(rlake['lake'], layer_name)
                if lake_layer.isValid():
                    QgsProject.instance().addMapLayer(lake_layer)
                    result['rlake_volume'] = self._raster_volume(rlake['lake'], cell_area)
                else:
                    lake_layer = None
            except Exception as e:
                QgsMessageLog.logMessage(self.tr("r.lake failed, falling back to numpy: {error}").format(
                                             error=str(e)),
                                         "Q-LandslideDam", Qgis.Warning)
                lake_layer = None
        else:
            QgsMessageLog.logMessage(self.tr("r.lake not available (GRASS provider not active), "
                                             "falling back to numpy."),
                                     "Q-LandslideDam", Qgis.Warning)

        # Ripiego: raster delle profondità calcolato in numpy
        if lake_layer is None:
            lake_layer = self.save_and_load_raster(
                numpy_array=depth,
                reference_layer=dem_layer,
                output_path=output_path,
                layer_name=layer_name,
                nodata_value=-9999.0
            )
        result['layer'] = lake_layer

        # Aggiunto dopo il raster del lago, così i punti restano visibili sopra di esso
        if add_control_points:
            self._add_control_points_layer(points, dem_layer.crs())

        volume_msg = f"Lake: numpy volume {volume:.1f} m³"
        if result['rlake_volume'] is not None:
            volume_msg += f" | volume r.lake {result['rlake_volume']:.1f} m³"
        QgsMessageLog.logMessage(volume_msg, "Q-LandslideDam", Qgis.Info)

        return result
